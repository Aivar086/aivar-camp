def analyze_fishing_weather(
    temp_max: float,
    temp_min: float,
    pressure_mm: float,
    wind_speed: float,
    precip_prob: int,
    moon_phase_name: str,
    target_species: str = None
) -> Dict[str, Any]:
    """
    Генерирует экспертные рекомендации AI-Егеря на основе метеоусловий и астрономии.
    """
    tactics = []
    lure_recommendations = []
    camp_recommendations = []
    warnings = []
    
    # Оценка давления
    if 752 <= pressure_mm <= 762:
        tactics.append("🎯 **Давление идеальное (норма)**: Рыба распределена по стандартным горизонтам. Хищник активен на утренней и вечерней зорьках, сазан и лещ уверенно берут со дна.")
    elif pressure_mm < 748:
        tactics.append("📉 **Пониженное давление (циклон)**: Перед приходом ненастья щука и крупный окунь могут впасть в кратковременный агрессивный жор. Мирная рыба (сазан, карась) прижимается ко дну и капризничает.")
        lure_recommendations.append("Используйте крупные шумные приманки (воблеры с погремушкой, виброхвосты 4.5-5\" темных оттенков).")
    else:
        tactics.append("📈 **Повышенное давление (антициклон)**: Вода прозрачнее, рыба пуглива и уходит на глубину (в русловые ямы и коряжники). Уменьшайте толщину поводков и размер крючков.")
        lure_recommendations.append("Ставьте пассивную резину (раки, слаги, черви) с медленной волочащейся проводкой по дну.")

    # Оценка ветра
    if wind_speed < 10:
        tactics.append("🌊 **Штиль**: Отличные условия для ловли на поверхностные приманки (попперы, волкеры, лягушки на змееголова) и комфортного заброса легких снастей.")
    elif 10 <= wind_speed <= 22:
        tactics.append("💨 **Умеренный прибой**: Наветренный берег — самое перспективное место! Волна вымывает корм, туда стягивается белая рыба, а за ней судак и жерех.")
    else:
        warnings.append("⚠️ **Сильный ветер**: Выход на надувной лодке на открытую воду крайне опасен. Ищите тихие заливы, протоки и камышовые заводи.")
        camp_recommendations.append("Укрепите все колышки палатки, поставьте авто с наветренной стороны как ветрозащиту.")

    # Оценка осадков
    if precip_prob > 50:
        warnings.append("🌧️ **Высокая вероятность дождя**: Проверьте герметичность чехлов и просушите вещи до захода солнца.")
        camp_recommendations.append("Натяните кемпинговый тент над столовой зоной и окопайте палатку небольшим водоотводным ровиком.")

    # Фаза Луны
    tactics.append(f"🌙 **Фаза Луны ({moon_phase_name})**: Оказывает влияние на ночную активность сазана и сома на донные снасти.")

    # По видам рыб
    if target_species:
        spec = target_species.lower()
        if "судак" in spec:
            tactics.append("🐟 **По судаку**: Лучшее время — за 40 минут до рассвета и в сумерках. Основные точки — ракушечные бровки на глубине 5-8м, джиг ступенькой с паузой 2-3 сек.")
        if "сазан" in spec:
            tactics.append("🐟 **По сазану**: Закормите точку вареной кукурузой с глиной и жмыхом за 3-4 часа до ловли. В качестве насадки — волосяная оснастка с бойлом или «бутерброд» кукуруза+опарыш.")
        if "жерех" in spec:
            tactics.append("🐟 **По жереху**: Ищите характерные удары («котлы») на перекатах и струе. Дальнобойные пилькеры (Кастмастер 21-28г) на сверхбыстрой проводке у поверхности.")
        if "змееголов" in spec:
            tactics.append("🐟 **По змееголову**: Ищите плотные ковры травы и кувшинок на мелководье (0.5-1.5м), плавающая незацепляйка-лягушка с паузами при прохождении окон.")

    return {
        "status": "success",
        "tactics": tactics,
        "lure_recommendations": lure_recommendations,
        "camp_recommendations": camp_recommendations,
        "warnings": warnings
    }

